#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const repoRoot = process.cwd();
const map = JSON.parse(await readFile(path.join(repoRoot, 'docs/sync/alembic-code-map.json'), 'utf8'));
const facts = JSON.parse(await readFile(path.join(repoRoot, 'docs/_generated/alembic-facts.json'), 'utf8'));

function escapeCell(value) {
  return String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, '<br>');
}

function code(value) {
  return `\`${value}\``;
}

function list(items = []) {
  if (!items.length) {
    return '- 本章没有额外人工断言，依赖代码锚点表继续追踪。';
  }
  return items.map((item) => `- ${item}`).join('\n');
}

function finish(lines) {
  return `${lines.join('\n').replace(/\n+$/u, '')}\n`;
}

function anchorFacts(chapter) {
  return (chapter.anchors ?? []).map((rel) => facts.fileFacts[rel] ?? { relPath: rel, exists: false });
}

function symbolsFor(file) {
  if (!file.exists) {
    return '缺失';
  }
  const s = file.symbols ?? {};
  const names = [
    ...(s.exported ?? []),
    ...(s.classes ?? []).filter((name) => !(s.exported ?? []).includes(name)),
    ...(s.functions ?? []).filter((name) => !(s.exported ?? []).includes(name)),
  ];
  return names.slice(0, 6).map(code).join(', ') || '未抽取到导出符号';
}

function anchorTable(chapter) {
  const rows = anchorFacts(chapter);
  if (rows.length === 0) {
    return '本页不直接锚定代码文件。';
  }
  return [
    '| Alembic 文件 | 状态 | 主要符号 |',
    '| --- | --- | --- |',
    ...rows.map((file) => {
      const status = file.exists ? `${file.lineCount} 行 · ${file.sha256}` : '缺失';
      return `| ${escapeCell(code(file.relPath))} | ${escapeCell(status)} | ${escapeCell(symbolsFor(file))} |`;
    }),
  ].join('\n');
}

function imageBlock(chapter) {
  const images = chapter.images ?? [];
  if (!images.length) {
    return '';
  }
  return images
    .map((image) => `![${image.alt}](${image.src})\n\n*${image.caption ?? image.alt}*`)
    .join('\n\n');
}

function generatedNotice() {
  return [
    '<!--',
    '  AUTO-GENERATED BY scripts/rewrite-book-from-facts.mjs.',
    '  Edit docs/sync/alembic-code-map.json and rerun npm run sync:book.',
    '-->',
  ].join('\n');
}

function chapterPage(chapter) {
  const parts = [];
  parts.push(generatedNotice());
  parts.push('');
  parts.push(`# ${chapter.title}`);
  parts.push('');
  if (chapter.thesis) {
    parts.push(chapter.thesis);
    parts.push('');
  }
  const images = imageBlock(chapter);
  if (images) {
    parts.push(images);
    parts.push('');
  }
  parts.push('## 同步状态');
  parts.push('');
  parts.push(`本章内容已按 Alembic 代码重写，锚定提交 ${code(facts.alembicCommit)}。同步脚本会记录每个锚点文件的行数、短哈希和主要符号；如果 Alembic 代码变化，运行 ${code('npm run sync:book')} 会重新生成本页。`);
  if (facts.alembicDirty) {
    parts.push('');
    parts.push(`> 当前 Alembic 工作区生成时不是干净状态：${code(facts.alembicDirty.replace(/\n/g, '; '))}`);
  }
  parts.push('');
  parts.push('## 代码锚点');
  parts.push('');
  parts.push(anchorTable(chapter));
  parts.push('');
  parts.push('## 本章结论');
  parts.push('');
  parts.push(list(chapter.checkpoints));
  parts.push('');
  parts.push('## 真实实现链路');
  parts.push('');
  parts.push(list(chapter.implementation));
  parts.push('');
  parts.push('## 门控与边界');
  parts.push('');
  parts.push(list(chapter.gates));
  parts.push('');
  parts.push('## 易漂移点');
  parts.push('');
  parts.push(list(chapter.drift));
  parts.push('');
  parts.push('## 从代码继续读');
  parts.push('');
  const readOrder = chapter.readOrder?.length ? chapter.readOrder : chapter.anchors;
  parts.push(list((readOrder ?? []).map((rel) => `${code(rel)}：${chapter.readingHint ?? '从入口方法、构造依赖和导出类型开始核对本章叙述。'}`)));
  parts.push('');
  parts.push('## 抽取到的符号索引');
  parts.push('');
  for (const file of anchorFacts(chapter).filter((item) => item.exists)) {
    const s = file.symbols ?? {};
    const groups = [
      ['导出', s.exported],
      ['类', s.classes],
      ['函数', s.functions],
      ['方法', s.methods],
      ['常量', s.constants],
    ]
      .filter(([, values]) => values?.length)
      .map(([label, values]) => `${label}: ${values.slice(0, 10).map(code).join(', ')}`);
    parts.push(`- ${code(file.relPath)}${groups.length ? ` — ${groups.join('；')}` : ''}`);
  }
  parts.push('');
  return finish(parts);
}

function indexPage() {
  const chapterCount = map.chapters.filter((chapter) => chapter.type === 'chapter').length;
  const appendixCount = map.chapters.filter((chapter) => chapter.type?.startsWith('appendix')).length;
  return `${generatedNotice()}

# Alembic 技术解构

这版 book 不再把 Alembic 当成静态产品介绍，而是把它当成一个会进化的工程系统来读：每一章都从真实代码锚点生成，先讲入口、状态、门控和失败分支，再把工程判断沉到可追踪的文件表里。

## 这次重写的原则

- 以 Alembic 提交 ${code(facts.alembicCommit)} 为事实源，覆盖 ${chapterCount} 个正文篇章和 ${appendixCount} 个附录。
- 不手写“看起来合理”的架构图谱；每页都列出实际代码文件、行数、短哈希和抽取到的符号。
- 对进化、Agent、Tool V2、Workflow、VSCode 文件监听、MCP 写入工具、Dashboard/API 等高漂移区域，优先记录判断分叉和门控条件。
- 插图作为阅读锚点保留，文字改为服务于代码链路；后续插图提示词可以继续从这些章节事实反推。

## 阅读路线

| 阶段 | 建议读法 |
| --- | --- |
| 起点与哲学 | 先读本地记忆主权和 SOUL，再看 CLI/setup 如何把原则落到磁盘、权限和 Constitution。 |
| 工程基石 | 从 DI、AST、Project Intelligence 和 Guard 进入，理解 Alembic 怎样把项目变成可审计事实。 |
| 知识领域 | 重点读 KnowledgeEntry、ConfidenceRouter、生命周期、EvolutionGateway、ProposalExecutor 和 Quality/Dimension。 |
| 核心服务 | 串起 Cold Start、Rescan、Search、Vector、Panorama、Signal 和 Metabolism。 |
| Agent 智能层 | 重点看 AgentRuntime、Profile/Capability/Strategy/Policy 正交组合，以及 Tool System V2。 |
| 平台与交付 | 用 MCP、HTTP、Dashboard、VSCode extension 和 Delivery 管线检查外部 Agent 如何接入。 |

## 同步命令

\`\`\`bash
npm run sync:book
npm run build
\`\`\`

生成物位于 ${code('docs/_generated/alembic-facts.json')} 与 ${code('docs/_generated/alembic-facts.md')}。如果 Alembic 代码改了，${code('npm run sync:check')} 会用锚点哈希提醒 book 已经落后。
`;
}

function visualTourPage() {
  const imageChapters = map.chapters.filter((chapter) => chapter.images?.length);
  const lines = [];
  lines.push(generatedNotice(), '', '# 图解速览', '');
  lines.push(`这一页只做插图导航。所有图片文件保持不变，说明文字来自当前代码锚点清单，便于后续统一调整提示词和替换标准图。`, '');
  for (const chapter of imageChapters) {
    lines.push(`## ${chapter.title}`, '');
    if (chapter.thesis) {
      lines.push(chapter.thesis, '');
    }
    for (const image of chapter.images) {
      lines.push(`![${image.alt}](${image.src})`, '');
      lines.push(`*${image.caption ?? image.alt}*`, '');
    }
  }
  return finish(lines);
}

function appendixMcp(chapter) {
  const lines = [];
  lines.push(generatedNotice(), '', `# ${chapter.title}`, '');
  lines.push(chapter.thesis ?? 'MCP 工具清单由 Alembic 源码抽取生成。', '');
  lines.push('## 工具总览', '');
  lines.push('| 工具 | Gateway 动作 | 资源 | 注册状态 |');
  lines.push('| --- | --- | --- | --- |');
  for (const tool of facts.mcp.declaredTools) {
    const gate = facts.mcp.gatewayEntries.find((entry) => entry.tool === tool);
    const registered = facts.mcp.registeredHandlers.includes(tool) ? '已注册' : '声明未在 McpServer 直接匹配';
    const action = gate?.action
      ? `${gate.resolver ? 'resolver: ' : ''}${code(gate.action)}`
      : gate?.resolver
        ? 'resolver'
        : '读操作';
    lines.push(`| ${code(tool)} | ${action} | ${gate?.resource ? code(gate.resource) : ''} | ${registered} |`);
  }
  lines.push('', '## Schema 导出', '', list(facts.mcp.schemaExports.map((name) => code(name))));
  lines.push('', '## 代码锚点', '', anchorTable(chapter), '');
  lines.push('## 维护判断', '', list(chapter.checkpoints), '', '## 易漂移点', '', list(chapter.drift), '');
  return finish(lines);
}

function appendixConfig(chapter) {
  const lines = [];
  lines.push(generatedNotice(), '', `# ${chapter.title}`, '');
  lines.push(chapter.thesis ?? '配置参考由 CLI、Setup、ConfigLoader 和 Defaults 的真实入口生成。', '');
  lines.push('## CLI 命令', '');
  lines.push('| 命令 | 签名 |');
  lines.push('| --- | --- |');
  for (const cmd of facts.cli) {
    lines.push(`| ${code(cmd.command)} | ${code(cmd.signature)} |`);
  }
  lines.push('', '## 配置链路', '', list(chapter.implementation));
  lines.push('', '## 代码锚点', '', anchorTable(chapter), '');
  lines.push('## 门控与边界', '', list(chapter.gates), '');
  return finish(lines);
}

function appendixSignals(chapter) {
  const lines = [];
  lines.push(generatedNotice(), '', `# ${chapter.title}`, '');
  lines.push(chapter.thesis ?? '信号类型清单由 Lifecycle、SignalBus、ProposalExecutor 与 VSCode 文件监听入口生成。', '');
  lines.push('## 生命周期状态', '');
  lines.push('| 常量 | 值 |');
  lines.push('| --- | --- |');
  for (const state of facts.lifecycle.states) {
    lines.push(`| ${code(state.name)} | ${code(state.value)} |`);
  }
  lines.push('', '## 生命周期转移', '');
  for (const edge of facts.lifecycle.transitions) {
    lines.push(`- ${code(edge.from)} → ${edge.to.map(code).join(', ')}`);
  }
  lines.push('', '## 文件变化信号源', '', list(facts.interfaces.fileChangeSignals.map((name) => code(name))));
  lines.push('', '## 代码锚点', '', anchorTable(chapter), '');
  lines.push('## 维护判断', '', list(chapter.checkpoints), '');
  return finish(lines);
}

function appendixGuard(chapter) {
  return chapterPage(chapter);
}

async function writeDoc(chapter) {
  let body;
  if (chapter.type === 'index') {
    body = indexPage();
  } else if (chapter.type === 'visual-tour') {
    body = visualTourPage();
  } else if (chapter.type === 'appendix-mcp') {
    body = appendixMcp(chapter);
  } else if (chapter.type === 'appendix-config') {
    body = appendixConfig(chapter);
  } else if (chapter.type === 'appendix-signals') {
    body = appendixSignals(chapter);
  } else if (chapter.type === 'appendix-guard') {
    body = appendixGuard(chapter);
  } else {
    body = chapterPage(chapter);
  }
  const abs = path.join(repoRoot, chapter.path);
  await mkdir(path.dirname(abs), { recursive: true });
  await writeFile(abs, body);
}

for (const chapter of map.chapters) {
  await writeDoc(chapter);
}

console.log(`[sync:rewrite] rewrote ${map.chapters.length} book files from Alembic ${facts.alembicCommit}`);
